import assert from 'node:assert/strict';
import { EMPTY_BOARD_FILTERS, hasBoardFilters, matchesBoardTask } from '../src/utils/board-filters.js';
const task={title:'Plan the launch',done:false,dueAt:'2026-01-01T12:00:00Z',labels:[{id:'product'}],assignees:[{label:'Alex'}]};
const now=Date.parse('2026-02-01T12:00:00Z');
const matches=changes=>matchesBoardTask(task,'backlog',{...EMPTY_BOARD_FILTERS,...changes},'Description text beyond the card preview. Acceptance criteria.',now);
assert.equal(hasBoardFilters(EMPTY_BOARD_FILTERS),false);
assert.equal(hasBoardFilters({...EMPTY_BOARD_FILTERS,search:'   '}),false);
assert.equal(hasBoardFilters({...EMPTY_BOARD_FILTERS,status:'open'}),true);
assert.equal(matches({search:'ACCEPTANCE'}),true);
assert.equal(matches({search:'launch'}),true);
assert.equal(matches({search:'missing'}),false);
assert.equal(matches({stage:'backlog',label:'product',status:'open',assignment:'assigned',due:'overdue'}),true);
for(const filter of [{stage:'review'},{label:'other'},{status:'completed'},{assignment:'unassigned'},{due:'none'}])assert.equal(matches(filter),false);
assert.equal(matches({due:'scheduled'}),true);
assert.equal(matchesBoardTask({...task,done:true},'backlog',{...EMPTY_BOARD_FILTERS,due:'overdue'},'',now),false);
assert.equal(matchesBoardTask({title:'Minimal task',done:false},'backlog',{...EMPTY_BOARD_FILTERS,assignment:'unassigned',due:'none'},'',now),true);
assert.equal(matchesBoardTask({...task,dueAt:new Date(now).toISOString()},'backlog',{...EMPTY_BOARD_FILTERS,due:'overdue'},'',now),false);
assert.equal(task.done,false);assert.equal(task.labels[0].id,'product');
console.log('PASS: board search/full-description input, combined filters, optional fields, overdue boundaries, completed exclusion and immutable canonical task data.');
